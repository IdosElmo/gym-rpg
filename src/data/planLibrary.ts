const BY_LOCATION: Readonly<Record<Location, typeof GYM>> = {
  gym: GYM,
  home_dumbbells: HOME_DB,
  home_none: HOME_NONE,
};

/**
 * All 30 templates, in sheet order: location (gym, home + dumbbells, no
 * equipment), then days (2…6), then the men's and the women's variation.
 */
export const PLAN_TEMPLATES: readonly PlanTemplate[] = LIBRARY_LOCATIONS.flatMap((location) =>
  LIBRARY_DAYS.flatMap((days) =>
    LIBRARY_SEXES.map(
      (sex): PlanTemplate => ({
        id: libraryId(days, location, sex),
        days,
        location,
        sex,
        week: BY_LOCATION[location][days][sex],
      }),
    ),
  ),
);

const BY_ID: ReadonlyMap<string, PlanTemplate> = new Map(PLAN_TEMPLATES.map((t) => [t.id, t]));

/** A template by its id, or `null`. */
export function templateById(id: string): PlanTemplate | null {
  return BY_ID.get(id) ?? null;
}

/** The template for one cell of the grid — always exists. */
export function templateFor(days: LibraryDays, location: Location, sex: LibrarySex): PlanTemplate {
  const t = BY_ID.get(libraryId(days, location, sex));
  if (!t) throw new Error(`no plan template ${libraryId(days, location, sex)}`);
  return t;
}
