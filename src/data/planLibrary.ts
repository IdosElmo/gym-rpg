/**
 * data/planLibrary.ts — the goal-based plan library: 30 ready-made templates.
 *
 * days per week {2, 3, 4, 5, 6} × where you train {gym, home with dumbbells,
 * home / outdoors with no equipment} × a men's and a women's variation.
 *
 *   2 days  Full Body A/B
 *   3 days  Full Body A/B/C
 *   4 days  Upper / Lower × 2
 *   5 days  Upper / Lower + Push / Pull / Legs
 *   6 days  Push / Pull / Legs × 2
 *
 * The two variations share the skeleton and the split. The women's version
 * moves volume toward glutes and legs (hip thrust / glute bridge, abduction,
 * kickback, RDL, lunges, band walks) and trims some heavy upper isolation; the
 * men's version keeps a little more chest / shoulder / arm volume. Both train
 * every body part every week (tests/planLibrary.test.ts counts it).
 *
 * THIS FILE IS DATA, AS AUTHORED for an intermediate trainee who wants to build
 * muscle. Everything a profile changes — goal, experience, session length,
 * injuries, the user's own weekdays — is applied when a plan is BUILT, by the
 * pure functions in `core/planLibrary.ts`. Nothing here is ever re-derived into
 * history: a built plan is an ordinary `plan_updated` document.
 *
 * EQUIPMENT RULE, per location (tested):
 *   home_none       → only exercises whose `equip` includes 'Bodyweight'
 *                     (a park bench / low bar / table is assumed);
 *   home_dumbbells  → 'Dumbbells', 'Bands' or 'Bodyweight';
 *   gym             → anything.
 *
 * Rows are `[exerciseId, sets, reps, restSeconds]`. Reps are the program's own
 * Hebrew scheme words ('10 לרגל', '30–45 שנ׳'), rendered in either language by
 * `repsText`. Day labels carry both languages; a plan is built in the language
 * on screen, and the label is the user's content from then on.
 */

import type { Location } from '../core/profile.ts';
import type { EquipmentKey } from './program.ts';

export type LibrarySex = 'm' | 'f';
export type LibraryDays = 2 | 3 | 4 | 5 | 6;

export const LIBRARY_DAYS: readonly LibraryDays[] = [2, 3, 4, 5, 6];
export const LIBRARY_LOCATIONS: readonly Location[] = ['gym', 'home_dumbbells', 'home_none'];
export const LIBRARY_SEXES: readonly LibrarySex[] = ['m', 'f'];

/** `[exerciseId, sets, reps, restSeconds]`. */
export type LibraryRow = readonly [id: string, sets: number, reps: string, rest: number];

export interface LibraryDay {
  /** Hebrew day label ("פול באדי A"). */
  readonly he: string;
  /** English day label ("Full Body A"). */
  readonly en: string;
  readonly rows: readonly LibraryRow[];
}

export interface PlanTemplate {
  /** `lib_<days>_<location>_<m|f>` — stable, the preset id. */
  readonly id: string;
  readonly days: LibraryDays;
  readonly location: Location;
  readonly sex: LibrarySex;
  /** One entry per workout day, in tab order. */
  readonly week: readonly LibraryDay[];
}

/** The template id for one cell of the grid. */
export function libraryId(days: LibraryDays, location: Location, sex: LibrarySex): string {
  return `lib_${days}_${location}_${sex}`;
}

/**
 * The weekday each day of a template is trained on when the user gave none
 * (0 = Sunday). Single days, never ranges, so the weekly target is the day
 * count. A user's own weekdays replace these (`onWeekdays`).
 */
export const LIBRARY_WEEKDAYS: Readonly<Record<LibraryDays, readonly number[]>> = {
  2: [0, 3], // Sun, Wed
  3: [0, 2, 4], // Sun, Tue, Thu
  4: [0, 1, 3, 4], // Upper Sun, Lower Mon, Upper Wed, Lower Thu
  5: [0, 1, 3, 4, 5], // Upper, Lower, (rest), Push, Pull, Legs
  6: [0, 1, 2, 3, 4, 5], // PPL ×2, Saturday off
};

/* ------------------------------------------------- what a location allows */

/** Does `equip` satisfy the location's equipment rule? */
export function equipAllowed(location: Location, equip: readonly EquipmentKey[]): boolean {
  if (location === 'gym') return true;
  if (location === 'home_none') return equip.includes('Bodyweight');
  return equip.includes('Dumbbells') || equip.includes('Bands') || equip.includes('Bodyweight');
}

