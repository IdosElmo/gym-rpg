/** The common unit words; a food overrides the ones that read differently. */
const U: Readonly<Record<string, string>> = {
  cup: 'cup',
  tbsp: 'tbsp',
  tsp: 'tsp',
  g100: '100 g',
  slice: 'slice',
  unit: 'pc',
  serving: 'serving',
  bowl: 'bowl',
  can: 'can',
  handful: 'handful',
  container: 'tub',
  half: 'half',
};

/** One overlay row: the English name and its units (`ids` space-separated, read from `U` unless overridden). */
function f(name: string, ids: string, over: Readonly<Record<string, string>> = {}): FoodEn {
  const units: Record<string, string> = {};
  for (const id of ids.split(' ')) {
    const label = over[id] ?? U[id];
    if (label) units[id] = label;
  }
  return { name, units };
}

